// Upcast повышает data типа eventType с версии from до версии to цепочкой шагов.
// Нет шага — ошибка (приём: карантин ingest.unknown_schema_version, AD-20).
func Upcast(eventType string, from, to int, data map[string]any) (map[string]any, error) {
	for v := from; v < to; v++ {
		found := false
		for _, s := range steps {
			if s.EventType == eventType && s.From == v {
				data = s.Fn(data)
				found = true
				break
			}
		}
		if !found {
			return nil, fmt.Errorf("upcast: нет повышателя %s v%d → v%d", eventType, v, v+1)
		}
	}
	return data, nil
}

func clone(in map[string]any) map[string]any {
	out := make(map[string]any, len(in))
	for k, v := range in {
		if m, ok := v.(map[string]any); ok {
			v = clone(m)
		}
		out[k] = v
	}
	return out
}

func split(p string) []string { return strings.Split(strings.TrimPrefix(p, "/"), "/") }

func getPath(m map[string]any, p string) any {
	parts := split(p)
	var cur any = m
	for _, k := range parts {
		mm, ok := cur.(map[string]any)
		if !ok {
			return nil
		}
		cur = mm[k]
	}
	return cur
}

func setPath(m map[string]any, p string, v any) {
	parts := split(p)
	for _, k := range parts[:len(parts)-1] {
		next, ok := m[k].(map[string]any)
		if !ok {
			next = map[string]any{}
			m[k] = next
		}
		m = next
	}
	m[parts[len(parts)-1]] = v
}

func deletePath(m map[string]any, p string) {
	parts := split(p)
	for _, k := range parts[:len(parts)-1] {
		next, ok := m[k].(map[string]any)
		if !ok {
			return
		}
		m = next
	}
	delete(m, parts[len(parts)-1])
}
