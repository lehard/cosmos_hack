type statusFile struct {
	Version      int       `yaml:"version"`
	Palette      yaml.Node `yaml:"palette"`
	Axes         yaml.Node `yaml:"axes"`
	Dictionaries yaml.Node `yaml:"dictionaries"`
}

type statusDict struct {
	Title     string `yaml:"title"`
	Owner     string `yaml:"owner"`
	ChangedBy string `yaml:"changed_by"`
	Values    []struct {
		Code  string `yaml:"code"`
		Label string `yaml:"label"`
		Tone  string `yaml:"tone"`
	} `yaml:"values"`
}

func genStatuses() error {
	var f statusFile
	if err := readYAML("contracts/statuses.yaml", &f); err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString(header("contracts/statuses.yaml", "statuses"))
	b.WriteString(`// Пакет statuses — словарь статусов изделия (PRD §3b, AD-30, NFR-UI-3): шесть осей
// с модулем-владельцем и дополнительные словари; одно перечисление на весь продукт.
//
// Слой: сгенерированные контракты — чистые данные; доступны домену (AD-1).
package statuses

// Value — значение оси или словаря: код, текст интерфейса, тон цвета.
type Value struct {
	Code  string
	Label string
	Tone  string
}

// Dictionary — ось статуса или словарь.
type Dictionary struct {
	Name   string
	Title  string
	Owner  string
	Values []Value
}

`)
	// Палитра.
	b.WriteString("// Palette — тон → цвет по умолчанию.\nvar Palette = [...][2]string{\n")
	for i := 0; i+1 < len(f.Palette.Content); i += 2 {
		var p struct {
			Color string `yaml:"color"`
		}
		if err := f.Palette.Content[i+1].Decode(&p); err != nil {
			return err
		}
		fmt.Fprintf(&b, "{%s, %s},\n", q(f.Palette.Content[i].Value), q(p.Color))
	}
	b.WriteString("}\n\n")
	emit := func(node yaml.Node, varName, what string) error {
		var all []string
		for i := 0; i+1 < len(node.Content); i += 2 {
			name := node.Content[i].Value
			var d statusDict
			if err := node.Content[i+1].Decode(&d); err != nil {
				return err
			}
			tn := camel(name)
			b.WriteString(comment(d.Title + " (" + what + ")."))
			fmt.Fprintf(&b, "type %s string\n\n", tn)
			fmt.Fprintf(&b, "// Значения %s.\nconst (\n", name)
			vals := make([]string, 0, len(d.Values))
			for _, v := range d.Values {
				b.WriteString(comment(v.Label))
				fmt.Fprintf(&b, "%s%s %s = %s\n", tn, camel(v.Code), tn, q(v.Code))
				vals = append(vals, fmt.Sprintf("{Code: %s, Label: %s, Tone: %s}", q(v.Code), q(v.Label), q(v.Tone)))
			}
			b.WriteString(")\n\n")
			all = append(all, fmt.Sprintf("{Name: %s, Title: %s, Owner: %s, Values: []Value{%s}}", q(name), q(d.Title), q(d.Owner), strings.Join(vals, ", ")))
		}
		fmt.Fprintf(&b, "// %s — %s в порядке файла.\nvar %s = [...]Dictionary{\n%s,\n}\n\n", varName, what, varName, strings.Join(all, ",\n"))
		return nil
	}
	if err := emit(f.Axes, "Axes", "ось статуса"); err != nil {
		return err
	}
	if err := emit(f.Dictionaries, "Dictionaries", "словарь"); err != nil {
		return err
	}
	return writeGo("backend/internal/contracts/statuses/statuses_gen.go", b.String())
}

// ------------------------------------------------------------ constants ----

func genConstants() error {
	var n yaml.Node
	if err := readYAML("contracts/constants.yaml", &n); err != nil {
		return err
	}
	doc := n.Content[0]
	var b strings.Builder
	b.WriteString(header("contracts/constants.yaml", "constants"))
	b.WriteString("// Пакет constants — константы контракта v1: NS_ANT, URI расширения BPMN, шаблоны\n// payloadType и QR, формат цепочки (AD-3, AD-10, AD-17, AD-44).\n//\n// Слой: сгенерированные контракты — чистые данные; доступны домену (AD-1).\npackage constants\n\nconst (\n")
	for i := 0; i+1 < len(doc.Content); i += 2 {
		k, v := doc.Content[i], doc.Content[i+1]
		b.WriteString(comment(strings.TrimLeft(k.HeadComment, "# ")))
		switch v.Tag {
		case "!!int":
			fmt.Fprintf(&b, "%s = %s\n", constName(k.Value), v.Value)
		default:
			fmt.Fprintf(&b, "%s = %s\n", constName(k.Value), q(v.Value))
		}
	}
	b.WriteString(")\n")
	src := b.String()
	// Комментарии YAML — многострочные с «# » в начале строк.
	src = strings.ReplaceAll(src, "\n// # ", "\n// ")
	src = regexp.MustCompile(`(?m)^// #\s?`).ReplaceAllString(src, "// ")
	return writeGo("backend/internal/contracts/constants/constants_gen.go", src)
}

