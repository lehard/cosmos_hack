// ---------------------------------------------------------------- общее ----

func path(p string) string { return filepath.Join(root, p) }

func readYAML(p string, v any) error {
	b, err := os.ReadFile(path(p))
	if err != nil {
		return err
	}
	return yaml.Unmarshal(b, v)
}

func header(src, pkg string) string {
	return "// Code generated by backend/tools/contractgen; DO NOT EDIT.\n" +
		"// Источник: " + src + " (make generate). Руками не править (AD-20).\n\n"
}

func writeGo(rel string, src string) error {
	out, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("%s: gofmt: %w\n%s", rel, err, src)
	}
	return writeFile(rel, out)
}

func writeFile(rel string, b []byte) error {
	p := path(rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return os.WriteFile(p, b, 0o644)
}

// camel: "item.item.registered" → "ItemItemRegistered", "NS_ANT" → "NsAnt".
func camel(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '.' || r == '_' || r == '-' || r == '/' || r == ' ' {
			up = true
			continue
		}
		if up {
			b.WriteRune(unicode.ToUpper(r))
			up = false
			continue
		}
		b.WriteRune(r)
	}
	out := b.String()
	if out != "" && unicode.IsDigit(rune(out[0])) {
		out = "N" + out
	}
	return out
}

// lowerAfterFirst: "NS_ANT" → "NsAnt" (для констант в верхнем регистре).
func constName(s string) string {
	parts := strings.Split(strings.ToLower(s), "_")
	for i, p := range parts {
		if p != "" {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

func q(s string) string { return strconv.Quote(s) }

func comment(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return ""
	}
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		if l = strings.TrimSpace(l); l == "" {
			lines[i] = "//"
		} else {
			lines[i] = "// " + l
		}
	}
	return strings.Join(lines, "\n") + "\n"
}

