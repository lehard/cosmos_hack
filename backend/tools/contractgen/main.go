// orderedMap — пары ключ → строка из узла YAML в порядке файла.
func orderedMap(n yaml.Node) [][2]string {
	var out [][2]string
	for i := 0; i+1 < len(n.Content); i += 2 {
		out = append(out, [2]string{n.Content[i].Value, n.Content[i+1].Value})
	}
	return out
}

func genCatalog() error {
	var c catalogFile
	if err := readYAML("contracts/events/catalog.yaml", &c); err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString(header("contracts/events/catalog.yaml", "catalog"))
	b.WriteString(`// Пакет catalog — каталог типов записей журнала (AD-40, AD-2, AD-27, AD-28, AD-30, AD-39):
// для каждого типа — единственный модуль-эмитент, вид записи, поток, ось статуса,
// класс действия, критичность, пометки guard_relevant и publish_stage.
//
// Слой: сгенерированные контракты — чистые данные; доступны домену (AD-1).
// Проверка «модуль эмитит чужой тип» опирается на Emitter (kernel.NewReaction,
// tools/emitcheck, проверка openapi.yaml).
package catalog

// Version — версия каталога.
`)
	fmt.Fprintf(&b, "const Version = %d\n\n", c.CatalogVersion)
	b.WriteString(`// Type — тип записи журнала ` + "`семейство.сущность.действие`" + `.
type Type string

// Kind — вид записи (AD-2).
type Kind string

// Виды записей.
const (
	KindFact     Kind = "fact"
	KindReaction Kind = "reaction"
	KindDecision Kind = "decision"
	KindService  Kind = "service"
)

// ActionClass — класс действия (AD-27); record — не действие.
type ActionClass string

// Классы действий.
const (
	ClassRecord       ActionClass = "record"
	ClassProtective   ActionClass = "protective"
	ClassPermissive   ActionClass = "permissive"
	ClassIrreversible ActionClass = "irreversible"
)

// Info — строка каталога для одного типа записи.
type Info struct {
	Type           Type
	Title          string
	Family         string
	Emitter        string
	Role           string
	Kind           Kind
	Stream         string
	Axis           string
	ActionClass    ActionClass
	Critical       bool
	CAGroup        string
	GuardRelevant  bool
	PublishStage   bool
	Provenance     []string
	Versions       []int
	CurrentVersion int
}

`)
	names := make([]string, 0, len(c.Types))
	for n := range c.Types {
		names = append(names, n)
	}
	slices.Sort(names)
	b.WriteString("// Типы записей каталога.\nconst (\n")
	for _, n := range names {
		t := c.Types[n]
		b.WriteString(comment(t.Title))
		fmt.Fprintf(&b, "%s Type = %s\n", camel(n), q(n))
	}
	b.WriteString(")\n\n")
	b.WriteString("// types — строки каталога, отсортированные по Type (для двоичного поиска).\nvar types = [...]Info{\n")
	for _, n := range names {
		t := c.Types[n]
		fam := strings.SplitN(n, ".", 2)[0]
		ca := ""
		if t.CAGroup != nil {
			ca = *t.CAGroup
		}
		fmt.Fprintf(&b, "{Type: %s, Title: %s, Family: %s, Emitter: %s, Role: %s, Kind: %s, Stream: %s, Axis: %s, ActionClass: %s, Critical: %v, CAGroup: %s, GuardRelevant: %v, PublishStage: %v, Provenance: %s, Versions: %s, CurrentVersion: %d},\n",
			camel(n), q(t.Title), q(fam), q(t.Emitter), q(t.Role), q(t.Kind), q(t.Stream), q(t.Axis), q(t.ActionClass), t.Critical, q(ca), t.GuardRelevant, t.PublishStage, strSlice(t.Provenance), intSlice(t.Versions), t.CurrentVersion)
	}
	b.WriteString("}\n\n")
	// Семейства.
	fams := make([]string, 0, len(c.Families))
	for f := range c.Families {
		fams = append(fams, f)
	}
	slices.Sort(fams)
	b.WriteString("// FamilyInfo — семейство типов и его модуль-владелец схемы (AD-40).\ntype FamilyInfo struct {\n\tFamily string\n\tOwner  string\n\tTitle  string\n}\n\n")
	b.WriteString("// families — семейства, отсортированные по имени.\nvar families = [...]FamilyInfo{\n")
	for _, f := range fams {
		fmt.Fprintf(&b, "{Family: %s, Owner: %s, Title: %s},\n", q(f), q(c.Families[f].Owner), q(c.Families[f].Title))
	}
	b.WriteString("}\n\n")
	// Модули, роли, потоки.
	b.WriteString("// ModuleInfo — модуль системы и его ответственность.\ntype ModuleInfo struct {\n\tName  string\n\tTitle string\n}\n\n")
	b.WriteString("// Modules — модули в порядке каталога.\nvar Modules = [...]ModuleInfo{\n")
	for _, kv := range orderedMap(c.Modules) {
		fmt.Fprintf(&b, "{Name: %s, Title: %s},\n", q(kv[0]), q(kv[1]))
	}
	b.WriteString("}\n\n")
	b.WriteString("// Roles — роли процесса, в которых исполняются функции-эмитенты (AD-40).\nvar Roles = [...]ModuleInfo{\n")
	for _, kv := range orderedMap(c.Roles) {
		fmt.Fprintf(&b, "{Name: %s, Title: %s},\n", q(kv[0]), q(kv[1]))
	}
	b.WriteString("}\n\n")
	b.WriteString("// Streams — виды потоков (AD-39).\nvar Streams = [...]ModuleInfo{\n")
	for _, kv := range orderedMap(c.Streams) {
		fmt.Fprintf(&b, "{Name: %s, Title: %s},\n", q(kv[0]), q(kv[1]))
	}
	b.WriteString("}\n\n")
	b.WriteString(`// Lookup возвращает строку каталога для типа.
func Lookup(t Type) (Info, bool) {
	lo, hi := 0, len(types)
	for lo < hi {
		m := (lo + hi) / 2
		if types[m].Type < t {
			lo = m + 1
		} else {
			hi = m
		}
	}
	if lo < len(types) && types[lo].Type == t {
		return types[lo], true
	}
	return Info{}, false
}

// All возвращает все строки каталога, отсортированные по типу.
func All() []Info { return types[:] }

// Families возвращает семейства, отсортированные по имени.
func Families() []FamilyInfo { return families[:] }

// Family возвращает семейство по имени.
func Family(name string) (FamilyInfo, bool) {
	for _, f := range families {
		if f.Family == name {
			return f, true
		}
	}
	return FamilyInfo{}, false
}

// EmittedBy сообщает, что тип t эмитит модуль module (AD-40: один эмитент на тип).
func EmittedBy(t Type, module string) bool {
	i, ok := Lookup(t)
	return ok && i.Emitter == module
}
`)
	return writeGo("backend/internal/contracts/catalog/catalog_gen.go", b.String())
}

func strSlice(ss []string) string {
	if len(ss) == 0 {
		return "nil"
	}
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = q(s)
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}

func intSlice(ns []int) string {
	if len(ns) == 0 {
		return "nil"
	}
	parts := make([]string, len(ns))
	for i, n := range ns {
		parts[i] = strconv.Itoa(n)
	}
	return "[]int{" + strings.Join(parts, ", ") + "}"
}

