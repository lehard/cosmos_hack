// Команда contractgen — генератор Go-кода и производных файлов из YAML- и
// JSON-источников contracts/ (AD-20, AD-40, AD-17; FR-110, FR-111; критерии О7, О8).
//
// Источники → результат:
//
//	contracts/events/catalog.yaml     → backend/internal/contracts/catalog/catalog_gen.go
//	contracts/errors.yaml             → backend/internal/contracts/errcodes/errcodes_gen.go
//	contracts/statuses.yaml           → backend/internal/contracts/statuses/statuses_gen.go
//	contracts/constants.yaml          → backend/internal/contracts/constants/constants_gen.go
//	contracts/events/upcasters/*.yaml → backend/internal/contracts/upcast/upcast_gen.go
//	contracts/events/**.v*.json       → backend/internal/contracts/events/registry_gen.go (тип+версия → Go-тип data)
//	contracts/bpmn-ext/ant.json       → backend/internal/contracts/bpmnext/bpmnext_gen.go,
//	                                    contracts/bpmn-ext/ant.xsd, docs/bpmn-ext-properties.md
//	contracts/**.json                 → backend/internal/contracts/schemas/** (копия для встраивания в бинарник)
//
// Go-типы данных событий и прочих JSON Schema генерирует go-jsonschema
// (deploy/scripts/generate-go.sh); contractgen дополняет их тем, чего
// go-jsonschema не умеет. Запуск — из каталога backend/tools:
//
//	go run ./contractgen -root ../..
//
// Детерминизм: всё сортируется, время и окружение в результат не попадают —
// повторный запуск даёт побайтно тот же вывод (make check: перегенерация +
