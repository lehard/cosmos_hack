// goTypeName повторяет правило go-jsonschema (--capitalization ID URL UUID JSON
// HTTP): слово заголовка, совпадающее с аббревиатурой, пишется заглавными.
func goTypeName(title string) string {
	words := regexp.MustCompile(`[A-Z][a-z0-9]*|[a-z0-9]+`).FindAllString(title, -1)
	for i, w := range words {
		switch strings.ToUpper(w) {
		case "ID", "URL", "UUID", "JSON", "HTTP":
			words[i] = strings.ToUpper(w)
		}
	}
	return strings.Join(words, "")
}

