func xsdType(t string) string {
	switch t {
	case "Boolean":
		return "xs:boolean"
	case "Integer":
		return "xs:integer"
	default:
		return "xs:string"
	}
}

func xmlEsc(s string) string {
	var b bytes.Buffer
	_ = xmlEscape(&b, s)
	return b.String()
}

func xmlEscape(b *bytes.Buffer, s string) error {
	r := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", "\"", "&quot;")
	_, err := b.WriteString(r.Replace(s))
	return err
}

