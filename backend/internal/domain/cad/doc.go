// Пакет cad — бизнес-правила модуля cad: импорт условной сборки КОМПАС-3D
// (FR-94, PRD §11.15, AD-18) на нашем языке.
//
// Что делает домен. Структура сборки, прочитанная адаптером из файла
// (infrastructure/integration/cad/kompas), превращается в объекты
// нормативного слоя (Translate):
//
//   - дерево компонентов с количествами (Tree) → черновики типов изделий
//     справочника (reference.item_type.defined утверждает человек, AD-31);
//   - связи сборки → зоны изделия и ограничения: шов W-1 — объект учёта
//     лимита ремонтов (FR-18), болтовое соединение J-1 — «закрывает доступ
//     к зоне» уплотнения (скрытые работы, FR-20), уплотнение S-1 — порядок
//     установки «до крышки» (предусловие, FR-17), резьбовое соединение —
//     момент затяжки и контровка;
//   - обозначения КД → внутренние ID типов изделий (ItemTypeID) и записи
//     соответствий `reference.external_id.mapped` (FR-95): КОМПАС и 1С
//     указывают на один наш тип; расхождение с номенклатурой 1С — отчёт,
//     без автосоздания (Discrepancies);
//   - отсутствие геометрии — явно (geometry: null → GeometryPresent = false
//     с пояснением, кейс §5.3).
//
// Слой: domain — чистые детерминированные функции без часов, случайности,
// float и ввода-вывода (AD-4); прочий доменный модуль: из домена импортирует
// только kernel, reference, signing, access (AD-1). Формат файла КОМПАС сюда
// не попадает — его переводит адаптер. Связи: вызывается из application/cad
// (операция cad.assembly.import, проекция cad.assembly) и независимым
// верификатором (AD-9).
//
// Требования: FR-94, FR-95, FR-17, FR-18, FR-20, FR-46; AD-17, AD-18, AD-31.
// Компонент кейса §3.2: Интеграции (§3.3, §5.3).
// Владелец: эпик 31 (Галактика, MES, КОМПАС-3D).
