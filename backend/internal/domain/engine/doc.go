// Пакет engine — движок: композиция свёртки изделия (AD-40) и гард операции
// над состоянием на basis_seq (AD-39).
//
// Fold(версия, вход) → состояние + реакции вызывает чистые функции модулей
// (Reduce, React) в фиксированном порядке item → process → vision → quality →
// machinelogs → documents → nonconformity → analysis → notifications; ранний
// модуль узнаёт вывод позднего только через свою функцию-намерение, которую
// вызывает поздний (process.AdvancePresentation, documents.Draft,
// quality.SetQuality, nonconformity.Contain); намерения применяют владельцы
// в конце шага (Apply). Своих типов записей движок не эмитит: задачи
// пересмотра (AD-3, AD-5) строятся типом task.task.created эмитента
// notifications.
//
// Слой: domain — последний в порядке импорта (AD-1); чистые функции (AD-4).
// Кроме свёртки здесь: сравнение вычисленных реакций со слотами записанных
// (Diff: слот, версия, отзыв; защитные не снимаются — задача пересмотра,
// AD-3), правило «решение принято до новых данных — пересмотрите» (AD-5,
// FR-32), свёртка префикса на момент (Prefix, FoldAt, AD-22) и хеш итога
// свёртки (StateHash, NFR-DET-1). Состояния модулей (State) обязаны
// сериализоваться в JSON целиком — экспортируемыми полями: по ним считается
// хеш состояния, который сверяют 1 и N воркеров, два процесса и верификатор.
//
// Связи: вызывается сценарием воркера application/engine, воспроизведением,
// заготовками при регрессии и верификатором (AD-9, AD-22).
//
// Требования: FR-2, FR-32, FR-40, FR-112, FR-124; AD-3, AD-4, AD-5, AD-39, AD-40.
