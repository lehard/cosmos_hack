// Пакет mes — бизнес-правила модуля mes: обмен с MES без повторного ручного
// ввода (FR-93, кейс §3.3) на нашем языке.
//
//   - Внутрь (через обычный приём, AD-18): задания MES → mes.job.received;
//     события операций → operation.run.started / paused / resumed / finished
//     того же изделия, что и у терминала исполнителя (история одна,
//     различается только источник факта, FR-140). Шаг процесса — по коду
//     операции нормативного слоя (BPMN `operationCode`); изделие, исполнитель,
//     оборудование MES — только по записям соответствий (FR-95); без
//     соответствия факт не выдумывается (FR-123), сообщение откладывается с причиной.
//   - Наружу: блокировки изделий и партий (PlanHold) — защитная реакция
//     сдерживания (ось nonconformity, AD-30) становится запросом mes.hold.requested
//     с бизнес-ключом ‹субъект›/hold|release/‹цикл›, чтобы заблокированное
//     изделие не получило следующую операцию в MES; снятие — только по
//     решению человека (AD-27). Квитанция MES — mes.hold.responded.
//
// Формат B2MML сюда не попадает — его переводит адаптер
// infrastructure/integration/mes/b2mml.
//
// Слой: domain — чистые детерминированные функции без часов, случайности,
// float и ввода-вывода (AD-4); прочий доменный модуль: из домена импортирует
// только kernel, reference, signing, access (AD-1). Связи: вызывается из
// application/mes (шлюз входящих, реакция «блок в MES», проекции) и
// независимым верификатором (AD-9).
//
// Требования: FR-93, FR-95, FR-123, FR-140; AD-18, AD-27, AD-30.
// Компонент кейса §3.2: Интеграции (§3.3).
// Владелец: эпик 31 (Галактика, MES, КОМПАС-3D).
