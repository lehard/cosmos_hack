// Пакет access — бизнес-правила модуля access: политика доступа «кто — что —
// над чем — где — когда» (AD-15, FR-78, FR-85).
//
// Здесь — чистые функции над данными политики, которые Casbin
// (infrastructure/security/casbin) регистрирует как свои функции, и свёртка
// политики из записей журнала policy.* и access.*:
//   - Roles.Closure — единственная функция наследования ролей: ею пользуются
//     вычислитель прав, столы ролей и модули, адресующие задачи по роли;
//   - ScopeCovers — сопоставление путей областей «здание → цех → участок →
//     рабочее место»;
//   - ValidAt — сроки полномочий по доменному времени (AD-37), вместо
//     встроенного timeMatch Casbin;
//   - ActionMatches — шаблоны действий `‹модуль›.‹объект›.‹действие›` с `*`;
//   - Policy.Apply — проекция политики из журнала; Seed — затравка до генезиса.
//
// Слой: domain — без часов, случайности, float и ввода-вывода (AD-4); базовый
// модуль: импортирует только kernel и контракты. Связи: вызывается из
// application/access, адаптера Casbin и независимым верификатором (AD-9).
//
// Требования: FR-78, FR-85, FR-128, FR-145; AD-15, AD-37.
// Владелец после волны 1: эпик 08, 26, 37.
