// Пакет erp — бизнес-правила модуля erp: порт учёта на нашем языке (AD-18),
// учётные действия на закрывающих точках, бизнес-ключ идемпотентности
// исходящих сообщений и их версии (AD-7), ось «учёт в 1С» (AD-30), смена
// склада при передаче изделия между цехами (FR-130).
//
// Порт учёта. На вход — «производственное задание», «справочник
// номенклатуры», «поступившая партия» (факты erp.order.received,
// erp.nomenclature.synced, erp.lot.received через обычный приём). На выход —
// «принято в работу», «смена склада», «перевод в брак» (переделка, списание,
// переработка), «возврат поставщику», «возврат из брака в производство»
// (решение Д-17), «выпуск» (с признаком after_rework и номером разрешения на
// отклонение), «результат контроля». Внутреннее движение по линии,
// блокировки, сигналы и наблюдения в 1С не уходят (кейс §3.3, PRD §4.11).
//
// Слой: domain — чистые детерминированные функции без часов, случайности,
// float и ввода-вывода (AD-4); прочий доменный модуль: из домена импортирует
// только kernel (AD-1). Связи: вызывается из application/erp (реакция
// роли projector «учётное сообщение сформировано», проекции, исходящие
// роли outbox) и независимым верификатором (AD-9). Форматы 1С сюда не
// попадают — перевод в qc.v1 и OData делает адаптер
// infrastructure/integration/erp/onec.
//
// Требования: FR-90, FR-91, FR-95, FR-96, FR-111, FR-130, AD-7, AD-18, AD-30.
// Компонент кейса §3.2: Интеграции (§3.3).
// Владелец: эпик 30 (1С), 31 (Галактика).
