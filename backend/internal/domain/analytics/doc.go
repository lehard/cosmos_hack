// Пакет analytics — бизнес-правила модуля analytics: вклады изделий в
// показатели, счётчики узлов, ограничение линии, аномалии и контрольные карты.
//
// Слой: domain — чистые детерминированные функции без часов, случайности,
// float и ввода-вывода (AD-4); прочий доменный модуль: из домена импортирует
// только kernel, reference, signing, access и сгенерированные контракты (AD-1).
//
// Устройство (AD-45, соглашения «Показатели», «Длительности», «Дефект»):
//   - Contribute — функция вклада изделия: вход изделия (записи журнала после
//     повышения версий) → строки вклада Row. Воркер заменяет строки изделия
//     целиком при каждой пересвёртке; агрегат — сумма строк (инкрементов нет),
//     поэтому повтор и позднее событие меняют показатель ровно на то, что
//     изменилось во входе изделия;
//   - EquipmentStep, IncidentStep — чистые свёртки глобальных проекций
//     (оборудование и инциденты — записи вне потока изделия);
//   - Nodes, Bottleneck, Anomalies — счётчики узлов по step_key, ограничение
//     линии и аномалии узлов (FR-2, FR-3, FR-5);
//   - PChart, XmRChart — контрольные карты Шухарта (ГОСТ Р ИСО 7870-2) в
//     целых числах.
//
// Связи: вызывается из application/analytics (вклады регистрирует движок —
// AddContributor в cmd/ant) и может вызываться верификатором (AD-9).
//
// Требования: FR-2, FR-3, FR-5, FR-86…FR-89, AD-45; кейс §2.4, §5.2.
// Компонент кейса §3.2: Централизованное ядро.
// Владелец: эпик 25 (аналитика).
