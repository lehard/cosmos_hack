// Пакет quality — бизнес-правила модуля quality: результаты контроля любого
// метода, сигналы, физические дефекты, полнота контроля, карта реакций,
// методы и покрытие видов дефектов, ось «состояние качества».
//
// Сердце контура «Решение по изделию» (кейс §2.3, §4.5; критерий О2/Т6):
// сигнал — не решение. Модуль понимает, что увидел метод и чего он увидеть не
// способен, и по карте реакций направляет изделие, никогда не выдавая «не
// обнаружено» за «годно».
//
//   - observe.go — единый тип результата контроля (FR-36): три исхода,
//     «оценка невозможна» с кодом причины (плохой кадр, прерванная обработка,
//     неизмеренная характеристика), измерения «значение против допуска» по
//     целым с масштабом; сигнал VisionQC как цепочка ступеней, уверенность и
//     качество наблюдения раздельно (FR-38); неизвестный вид — с флагом (FR-125).
//   - derive.go — физический дефект по ключу без вида (FR-37), сигналы,
//     полнота контроля (FR-35), покрытие видов методами (FR-14), пропуски
//     брака (FR-100), ось «состояние качества» (AD-30).
//   - assess.go — карта реакций: вид × тяжесть × уверенность × качество
//     наблюдения (FR-48) с ограничениями «ограничивать безопаснее, чем
//     разрешать» (FR-144, AD-27): режим правила (FR-50), класс действия,
//     уровень доверия паспорта анализатора (AD-29).
//   - requests.go — порт к поздним модулям композиции: черновик
//     несоответствия и сдерживание (nonconformity), задачи (notifications),
//     блокирующие причины для гарда точки предъявления.
//   - react.go — реакции quality.* (AD-3); frame.go — Reduce, React, Apply;
//     продвижение токена точки предъявления — функцией process (AD-40).
//
// Слой: domain — чистые детерминированные функции без часов, случайности,
// float и ввода-вывода (AD-4); модуль композиции свёртки изделия (AD-40): импортирует только доменные модули раньше себя в порядке kernel → reference → signing → access → item → process → vision → quality → machinelogs → documents → nonconformity → analysis → notifications → crossitem → engine.
// Связи: вызывается из application/quality, из свёртки (domain/engine) и
// независимым верификатором (AD-9).
//
// Требования: FR-14, FR-35…FR-38, FR-48, FR-50, FR-100, FR-125, FR-144, AD-3, AD-27, AD-29, AD-30.
// Компонент кейса §3.2: VisionQC (границы).
// Владелец: эпик 20 (качество).
