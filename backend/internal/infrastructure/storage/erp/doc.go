// Пакет erp — хранение модуля erp (зона storage, AD-1): своя схема Postgres
// «erp», свои миграции goose (migrations/, версии — метки времени).
//
//   - Очередь исходящих роли outbox (erp.outbox): строка сообщения глазами
//     журнала (пишет потребитель erp.outbox эффектом OutboxView в транзакции
//     курсора, AD-45) и транспортные поля попыток (пишет отправитель
//     эффектом OutboxTransport в транзакции ответа) — разные колонки, без
//     потерянных обновлений.
//   - Состояние каналов обмена (erp.channels) — операционное состояние сверки
//     ответной стороны (AD-18), не проекция журнала.
//   - Шлюз входящих: поданные факты и source_seq источника (erp.gateway_*).
//
// Проекции журнала модуля (erp.message, erp.item_accounting, …) — в хранении
// движка (engine.projections) эффектами Append. Чужих таблиц не читает; в
// журнал пишет только через порт journal (AD-44).
//
// Слой: infrastructure/storage; реализует ведомые порты application/erp;
// не импортирует другие зоны.
