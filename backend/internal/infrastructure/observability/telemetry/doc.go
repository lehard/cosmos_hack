//   - prometheus — /metrics в формате Prometheus (prometheus/client_golang):
//     операционные метрики — задержка и исходы приёма, дубли, карантин,
//     полнота (FR-41), «событие → экран» ant_event_to_sse_seconds (FR-2),
//     длительность свёртки, остановленные изделия, отставание потребителей
