// Пакет stand — stand MES — «эмулятор» кейса (AD-18, NFR-TEST-2, FR-93): та
// же HTTP-привязка B2MML-JSON (контракт mes.isa95.v1), что у MES или её
// интеграционной шины, собственное состояние, подтверждения ConfirmBOD и
// сбои. Роль процесса stands — одна копия; адаптер-клиент — пакет b2mml
// (эпик 31).
//
// Что имитирует (под /stand/mes/b2mml):
//   - GET about — релиз B2MML и версии контракта;
//   - POST SyncMaterialSubLot / SyncMaterialLot — блок (Disposition =
//     Restricted, QC-HOLD, «Изолятор ОТК») и снятие (UnRestricted) экземпляра
//     или партии; ответ — ConfirmBOD: успех, повтор того же BODID — успех с
//     Duplicate (второго блока нет), ошибка данных — ErrorType = Data,
//     нарушение схемы — ErrorType = Contract;
//   - GET outbox — сообщения MES для Главного: ProcessOperationsSchedule
//     (задание) и NotifyOperationsEvent (начало и конец операции);
//   - главное правило MES: заблокированный экземпляр (Restricted) не получает
//     следующей операции — кнопка «выдать операцию» отказывает, событие не
//     формируется; после снятия блока операция выдаётся;
//   - страница /stand/mes/ «глазами MES» с кнопками «выдать задание»,
//     «выдать операцию», «завершить операцию»;
//   - сбои со страницы тестовых сценариев через служебный порт stand-ов:
//     недоступность (offline — разрыв соединения), ошибка (error: код из
//     param — 503 по умолчанию; 4xx — ConfirmBOD с ErrorType = Data; match —
//     только для сообщения по образцу «hold:F-001» / «release:F-001» или
//     подстроке ID), задержка (delay, мс), дубль (duplicate: блок принят,
//     ответ потерян — повтор получает подтверждение Duplicate), несовместимая
//     шина (corrupt: about объявляет только mes.isa95.v2 — канал degraded).
//
// Граница эмуляции (чего нет): диспетчирования и расписания MES, учёта
// оборудования и персонала, брокера сообщений (только HTTP-привязка);
// состояние — в памяти процесса роли stands. Формат — проектное
// предположение (docs/integrations/mes.md).
//
// Слой: infrastructure/integration. Владелец: эпик 43.
