// Пакет stands — общий каркас stand-ов (AD-18, NFR-TEST-2, кейс §4.1):
// stand — «эмулятор» кейса, адаптер за тем же протоколом, что у реальной
// системы, с собственным состоянием, квитанциями и сбоями. Каркас даёт:
//
//   - FaultSwitch — сбои stand-а по таблице сбоев PRD §4.3 (недоступность,
//     задержка, повтор, пропуск, нарушение порядка, сдвиг часов, кривое
//     сообщение, ошибка) и их применение к входящим запросам и исходящим сообщениям;
//   - Registry — реестр stand-ов роли stands и реализация служебного порта
//     сбоев application/ingest.StandControl;
//   - Handler — HTTP роли stands: протоколы stand-ов под /stand/‹имя›/ и
//     служебный порт /stand/_control/ (сбои включает только страница тестовых
//     сценариев, AD-18);
//   - EquipmentStand — stand оборудования (сварочный источник, станок ЧПУ),
//     отдающий телеметрию edge-агенту по контракту
//     contracts/internal/stands/telemetry.v1.json (AD-46, FR-149).
//
// Stand-ы 1С, Галактики, MES, VisionQC (эпики 30–33, 43) регистрируются здесь
// же и получают сбои без собственного кода управления.
//
// Слой: infrastructure/integration; реализует ведомый порт application/ingest.StandControl.
// Владелец: эпик 06 (приём и edge-агент).
