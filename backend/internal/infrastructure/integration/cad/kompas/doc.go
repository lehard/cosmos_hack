// Пакет kompas — адаптер импорта условной сборки КОМПАС-3D модуля cad (зона
// integration, AD-18, AD-35): читает файл по контракту
// contracts/integrations/cad/assembly.schema.json (образец — сборка
// ФЛ-100.00.000 СБ, PRD §11.15) и переводит его в сборку на нашем языке
// (domain/cad.Assembly). Реализует ведомый порт application/cad.Reader.
//
//   - Файл сначала проверяется схемой контракта тем же валидатором, что у
//     приёма; нарушение — FormatError с полем (JSON Pointer): пропущенная
//     geometry, пустое обозначение, нет версии КД. Неизвестная мажорная
//     версия формата — FormatError{Version} (переобработка после повышателя).
//   - Геометрии нет — явно: geometry: null обязателен, пояснение — в
//     geometry_note (кейс §5.3).
//   - Числа файла, записанные дробью с нулевой частью (torque_nm: 12.0),
//     принимаются как целые; настоящая дробь — ошибка (AD-4: целое + масштаб).
//   - Отпечаток файла (Стрибог-256) — ключ идемпотентности импорта.
//
// Путь к прямому подключению (docs/integrations/kompas.md, §7): экстрактор
// COM API7 на Windows-шлюзе или выгрузка состава из ЛОЦМАН:PLM пишут тот же
// формат — меняется только источник файла, этот адаптер и ядро — нет.
//
// Требования: FR-94, FR-95, FR-111; AD-18, AD-20. Владелец: эпик 31.
