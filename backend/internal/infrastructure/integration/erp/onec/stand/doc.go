// Пакет stand — stand 1С:ERP — «эмулятор» кейса (AD-18, NFR-TEST-2, FR-91):
// тот же протокол, что у реальной 1С с расширением «КонтрольКачества»,
// собственное состояние, квитанции и сбои. Роль процесса stands — одна копия.
//
// Что имитирует:
//   - стандартный интерфейс OData v3 на чтение: `…/odata/standard.odata/$metadata`
//     (строится из манифеста контракта contracts/integrations/erp/1c — каркас
//     stand-а из контракта), номенклатура, склады, подразделения,
//     контрагенты, серии, «Этап производства», «Заказ на производство»,
//     «Приобретение товаров и услуг»; ошибки — телом `odata.error` с кодами 1С
//     (8 — тип не найден, 9 — экземпляр не найден);
//   - HTTP-сервис `…/hs/qc/v1/` на запись (контракт qc.v1): учётные действия и
//     результат контроля с ключом идемпотентности X-Message-Id — `202` и
//     квитанция, повтор — `200` и та же квитанция, `422` — ошибка данных,
//     `400` — нарушение контракта; по каждому принятому сообщению — документ
//     1С (перемещение, передача в производство, пересортица качества,
//     внутреннее потребление, порча, возврат поставщику, передача продукции
//     из производства, результат контроля), сторно при исправлении;
//   - собственное состояние: журнал обмена, документы, где числится изделие
//     и его качество («Новый» / «Не годен»); хранится в схеме Postgres
//     stand_onec (или в памяти — тесты);
//   - страница `/stand/1c/` «глазами 1С» в стиле интерфейса 1С «Такси»;
//   - сбои со страницы тестовых сценариев через служебный порт stand-ов:
//     недоступность (offline — разрыв соединения), ошибка (error: код из
//     param — 503 по умолчанию, 422 — ошибка данных; match — только для
//     сообщения по образцу «вид:субъект», например release_good:F-001),
//     задержка (delay, мс), дубль (duplicate: запись проведена, ответ
//     потерян — повтор получает ту же квитанцию; строки OData — дважды),
//     несовместимые метаданные (corrupt: реквизит «Статус» переименован — О8).
//
// Граница эмуляции (чего нет): проведения по регистрам ERP, себестоимости,
// остатков по количеству, прав пользователей 1С, плана обмена SelectChanges,
// конверта EnterpriseData; имена реквизитов — проектное предположение до
// сверки с базой предприятия (docs/integrations/1c.md, §9).
//
// Слой: infrastructure/integration. Владелец: эпик 30.
