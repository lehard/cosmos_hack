// Пакет onec — адаптер порта учёта для 1С:ERP (зона integration, AD-18,
// AD-35): OData v3 стандартного интерфейса на чтение (задания, номенклатура,
// партии, соответствия ID) и HTTP-сервис `/hs/qc/v1/` расширения
// «КонтрольКачества» на запись (учётные действия и результат контроля).
// Реализует ведомый порт application/erp.Ledger; внешние форматы (qc.v1,
// OData, `$metadata`) за пределы адаптера не выходят.
//
//   - Контракт — contracts/integrations/erp/1c: схемы qc.v1, манифест
//     ожидаемых метаданных, эталонные сообщения (встроены make generate в
//     contracts/schemas). Каждое исходящее сообщение до отправки проверяется
//     схемой контракта: ошибка интеграции видна до передачи в 1С (FR-111, О8).
//   - Сверка ответной стороны при старте: `$metadata` против манифеста и
//     версия контракта сервиса qc; расхождение — ContractError, канал degraded.
//   - Классы ответа: 202 — квитанция, 200 — повтор с той же квитанцией, 422 —
//     ошибка данных (карантин), 5xx/таймаут/разрыв — TransportError (повтор
//     с тем же X-Message-Id), 400 контракта и 401/403 — ContractError.
//
// Реальная 1С — сменой адреса и расширением конфигурации (docs/integrations/1c.md, §10).
// Stand — подпакет stand (роль stands).
//
// Требования: FR-90, FR-91, FR-95, FR-96, FR-111; AD-7, AD-18, AD-20.
