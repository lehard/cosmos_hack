// Пакет stand — stand Галактика ERP 9.x — «эмулятор» кейса (AD-18,
// NFR-TEST-2, FR-92): тот же контракт gal.qc.v1, что у обработчика на
// стороне Галактики, собственное состояние, квитанции GalAck и сбои. Роль
// процесса stands — одна копия; адаптер-клиент — пакет galaktika (эпик 31).
//
// Что имитирует (оба транспорта контракта):
//   - каталог обмена (exchange-dir, основной путь для 9.x): stand объявляет
//     версию контракта файлом about.xml, забирает пакеты Главного из out/,
//     кладёт квитанцию в ack/‹номер›.xml, свои пакеты (задания, партии) — в
//     in/, квитанции Главного на них читает из in-ack/;
//   - REST-фасад «под Галактика ESB» (rest-facade) под /stand/galaktika/esb/v1:
//     GET about, POST quality/lot-results и production/postings с
//     X-Message-Id — 202 и квитанция, повтор — 200 и та же квитанция
//     (duplicate), 422 — ошибка данных, 400 — нарушение контракта;
//     GET exchange/outbox — пакеты Галактики для Главного;
//   - документы Галактики по каждому принятому пакету (акт контроля качества,
//     требование-накладная, накладная на внутреннее перемещение, акт о браке,
//     возвратная накладная, сдача продукции), сторно при исправлении;
//   - страница /stand/galaktika/ «глазами Галактики» с кнопками «выдать
//     сменное задание» и «поступила партия»;
//   - сбои со страницы тестовых сценариев через служебный порт stand-ов:
//     недоступность (offline: разрыв соединения фасада; каталог не
//     обрабатывается — квитанций нет), ошибка (error: код из param — 503 по
//     умолчанию, 422 — ошибка данных квитанцией; match — только для пакета по
//     образцу «вид:субъект», например release:F-001), задержка (delay, мс),
//     дубль (duplicate: пакет принят, ответ фасада потерян — повтор получает
//     ту же квитанцию), несовместимый обработчик (corrupt: about объявляет
//     только gal.qc.v2 — канал degraded).
//
// Граница эмуляции (чего нет): проводок, складских остатков и себестоимости
// Галактики, VIP-интерфейса «Атлантиса», прав пользователей; состояние — в
// памяти процесса роли stands (квитанции каталога обмена переживают
// перезапуск в томе). Форматы — проектные предположения
// (docs/integrations/galaktika.md).
//
// Слой: infrastructure/integration. Владелец: эпик 43.
