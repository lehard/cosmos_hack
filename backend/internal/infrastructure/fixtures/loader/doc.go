// Пакет loader — общий загрузчик мира заготовок (служебная зона fixtures,
// AD-36, AD-38; FR-129, FR-150).
//
// Слой: infrastructure/fixtures. Импортирует только порты application
// (platform.FixtureCursor, коды ошибок) и сгенерированные контракты; зоны
// storage и transport не импортирует (AD-1): курсор в Postgres подаёт cmd/*
// через SetCursor, без него работает курсор в памяти (одна копия api).
//
// Что здесь:
//   - формат заготовок scenarios/fixtures/‹сценарий›/{scenario.yaml,steps/NN.yaml}
//     и общих ответов scenarios/fixtures/common/responses.yaml (format.go);
//   - библиотека сценариев: разрешение ответа «операция + параметры» на шаге —
//     шаги накопительные, файл шага несёт только изменившиеся ответы (library.go);
//   - префикс прогона: ID в заготовках хранятся без префикса, адаптер добавляет
//     ‹run_id›/ к локальной части в ответе и снимает его во входных параметрах (prefix.go);
//   - Runtime — мир заготовок процесса: библиотека + курсор; момент as_of — шаг
//     курсора (или последний шаг с часами ≤ as_of), команды пульта: старт, шаг,
//     переход, пауза, продолжение; решение человека на шаге ожидания двигает
//     курсор дальше (runtime.go);
//   - встроенный мир (Builtin): генератор пакета world строит те же сценарии в
//     памяти — образ ant не несёт каталога scenarios/, а заготовки должны
//     отвечать сразу; ANT_FIXTURES_DIR — читать каталог файлов.
//
// Модульные адаптеры infrastructure/fixtures/‹модуль› берут Default() и
// отвечают через Respond; прав, гардов и допустимых действий здесь нет — это
// общий декоратор application/access.Gate.
//
// Владелец: эпик 09; после волны 2 данные scenarios/fixtures переходят эпику 32.
package loader
