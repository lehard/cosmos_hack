/**
 * Реестр окна записи (Д-70): тип записи из `?open=‹тип›:‹id›` → содержимое окна.
 * Содержимое — готовые виджеты (карточка несоответствия, паспорт изделия,
 * панель решения), поставленные во вкладки и нижнюю панель окна; их логика не
 * меняется, запись приходит срезом (`nc_id`, `item_id`), а не выбором на столе.
 *
 * Какие типы есть в списках столов:
 * - `nonconformity` — строки очереди «Ждут моего решения» с несоответствием
 *   (сигнал, изолированное изделие), ссылки паспорта, уведомлений, задач,
 *   «требует внимания»: карточка + «Паспорт изделия», внизу — «Что решить»;
 * - `item` — точки предъявления без несоответствия, поиск в шапке, изделия на
 *   карте, постах, в раскрытии показателя, терминале: паспорт изделия.
 * - `workplace` — строки панели «Посты»: что на посту сейчас, назначения в
 *   смене, история поста (журнал потока `workplace:‹id›`);
 * - `person` — назначенный на пост сотрудник (панель «Посты», окно поста):
 *   профиль, роли, пост сейчас, квалификации;
 * - `integration` — строки экрана «Интеграции» стола администратора (эпик 48,
 *   FR-157): состояние, канал, ошибки, карантин, кнопки включения.
 * - `document` — строки реестра документов (раздел «Документы»): маршрут
 *   подписей, содержимое, версии, «Подписать / Отказать / Печать с QR / Скачать».
 * Заявка на решение редкого подписанта — это сам стол согласующего (одна
 * карточка с подписью), паспорт изделия из неё открывается окном `item`.
 * Новый тип — строка здесь и компонент в kinds/.
 */
import type { Component } from 'vue'

export interface RecordKindDefinition {
  /** Ленивая загрузка содержимого окна. */
  load: () => Promise<{ default: Component }>
}

export const recordKinds: Record<string, RecordKindDefinition> = {
  nonconformity: { load: () => import('./kinds/NonconformityRecord.vue') },
  item: { load: () => import('./kinds/ItemRecord.vue') },
  workplace: { load: () => import('./kinds/WorkplaceRecord.vue') },
  person: { load: () => import('./kinds/PersonRecord.vue') },
  integration: { load: () => import('./kinds/IntegrationRecord.vue') },
  document: { load: () => import('./kinds/DocumentRecord.vue') },
}

/** Типы, которые окно умеет показывать. */
export const RECORD_KINDS: ReadonlySet<string> = new Set(Object.keys(recordKinds))
